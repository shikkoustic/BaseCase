// topic placement follows the same pattern-based grouping used by
// well-known community sheets (Striver's A2Z/SDE sheet, NeetCode, Blind 75),
// e.g. grid DFS/BFS/union-find problems live under Graphs, not Arrays.
// CodeChef problems were pulled live from codechef.com/api/list/problems,
// keyword-matched per topic; counts are sized to the depth that topic
// actually gets on a competitive-programming judge — thin for
// interview-framed topics (Linked List, Heaps), strong for algorithmic
// ones (DP, Graphs, Math). CodeChef difficulty is a heuristic from its
// own success-rate stats (CodeChef does not publish a difficulty label).
// Per-topic counts are weighted by real-world interview importance:
// Sliding Window ~30, DP ~65, Graphs ~60, most others in between.

